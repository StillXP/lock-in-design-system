// Builds platform outputs from src/:
//   dist/css/tokens.css            CSS custom properties (light + dark + reduced motion)
//   dist/css/typography.css        .ds-text-* utility classes
//   dist/fonts/                    Inter + JetBrains Mono font files and licenses (copied from src/fonts/); the @font-face rules are inlined into every token sheet
//   dist/css/themes/<name>.css     complete token sheet for each project theme
//   dist/js/index.js (+ .d.ts)     resolved values for JS/TS (web), cssVars helper
//   dist/native/index.js (+ .d.ts) React Native ready values (numbers, RN shadows)
//   dist/json/*.json               resolved trees + flat AI-friendly index
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import {
  PACKAGE_ROOT, SRC_DIR, MODES, loadTokens, listThemes, resolveAll, cssVarName, nest,
} from '../lib/resolve.mjs';

const DIST = join(PACKAGE_ROOT, 'dist');
const REM_GROUPS = ['font.size.', 'space.', 'size.'];

let outDir = DIST;
const write = (rel, content) => {
  const file = join(outDir, rel);
  mkdirSync(join(file, '..'), { recursive: true });
  writeFileSync(file, content);
};

// ---------- CSS ----------

const quoteFont = (f) => (/\s/.test(f) && !f.startsWith('"') ? `"${f}"` : f);
const pxToRem = (v) => `${parseFloat(v) / 16}rem`;

function cssValue(path, entry, mode) {
  const { token } = entry;
  const value = entry.values[mode];
  const ref = entry.refs[mode];
  // Keep the alias chain visible in devtools: semantic -> base via var().
  if (ref && typeof value === 'string' && !token.extensions?.['ds.alpha']) return `var(${cssVarName(ref)})`;
  switch (token.type) {
    case 'dimension':
      return REM_GROUPS.some((g) => path.startsWith(g)) && value.endsWith('px') ? pxToRem(value) : value;
    case 'fontFamily':
      return Array.isArray(value) ? value.map(quoteFont).join(', ') : value;
    case 'cubicBezier':
      return `cubic-bezier(${value.join(', ')})`;
    case 'shadow':
      return `${value.offsetX} ${value.offsetY} ${value.blur} ${value.spread} ${value.color}`;
    case 'typography':
      return `${value.fontWeight} ${pxToRem(value.fontSize)}/${value.lineHeight} ${value.fontFamily.map(quoteFont).join(', ')}`;
    default:
      return String(value);
  }
}

function cssDecls(resolved, mode, filter) {
  const lines = [];
  for (const [path, entry] of resolved) {
    if (!filter(path, entry)) continue;
    lines.push(`  ${cssVarName(path)}: ${cssValue(path, entry, mode)};`);
    if (entry.token.type === 'typography') {
      lines.push(`  ${cssVarName(path)}-letter-spacing: ${entry.values[mode].letterSpacing};`);
    }
  }
  return lines.join('\n');
}

const modeDependent = (_, e) => JSON.stringify(e.values.light) !== JSON.stringify(e.values.dark);

function buildCss(resolved, banner, fontFaces) {
  const all = () => true;
  const durations = [...resolved.keys()].filter((p) => p.startsWith('motion.duration.'));
  return `/* ${banner} — generated by @lockin/tokens. Do not edit. */
${fontFaces}
:root,
[data-theme="light"] {
  color-scheme: light;
${cssDecls(resolved, 'light', all)}
}

[data-theme="dark"] {
  color-scheme: dark;
${cssDecls(resolved, 'dark', modeDependent)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${cssDecls(resolved, 'dark', modeDependent).replace(/^/gm, '  ')}
  }
}

@media (prefers-reduced-motion: reduce) {
  :root {
${durations.map((p) => `    ${cssVarName(p)}: 0ms;`).join('\n')}
  }
}
`;
}

function buildTypographyCss(resolved) {
  const rules = [...resolved]
    .filter(([, e]) => e.token.type === 'typography')
    .map(([path]) => {
      const cls = path.replace(/^typography\./, '').replace(/\./g, '-');
      return `.ds-text-${cls} {\n  font: var(${cssVarName(path)});\n  letter-spacing: var(${cssVarName(path)}-letter-spacing);\n}`;
    });
  return `/* Typography utility classes — generated by @lockin/tokens. */\n${rules.join('\n\n')}\n\n.ds-text-overline { text-transform: uppercase; }\n`;
}

// ---------- JS / native ----------

const parsePx = (v) => (typeof v === 'string' && /^-?[\d.]+px$/.test(v) ? parseFloat(v) : v);
const parseMs = (v) => (typeof v === 'string' && /^[\d.]+ms$/.test(v) ? parseFloat(v) : v);

function nativeValue(entry, mode) {
  const { token } = entry;
  const value = entry.values[mode];
  switch (token.type) {
    case 'dimension': return parsePx(value);
    case 'duration': return parseMs(value);
    case 'fontWeight': return String(value);
    case 'fontFamily': return token.extensions?.['ds.native'] ?? value[0];
    case 'shadow': {
      const m = value.color.match(/rgba\((\d+), (\d+), (\d+), ([\d.]+)\)/);
      const blur = parsePx(value.blur);
      return {
        shadowColor: m ? `rgb(${m[1]}, ${m[2]}, ${m[3]})` : value.color,
        shadowOpacity: m ? Number(m[4]) : 1,
        shadowOffset: { width: parsePx(value.offsetX), height: parsePx(value.offsetY) },
        shadowRadius: blur / 2,
        elevation: Math.round(blur / 3),
      };
    }
    case 'typography': {
      const fontSize = parsePx(value.fontSize);
      const ls = String(value.letterSpacing);
      return {
        fontFamily: undefined, // set by nativeFontFamily below
        fontSize,
        fontWeight: String(value.fontWeight),
        lineHeight: Math.round(fontSize * value.lineHeight),
        letterSpacing: ls.endsWith('em') ? Math.round(parseFloat(ls) * fontSize * 100) / 100 : parsePx(ls),
      };
    }
    default: return value;
  }
}

function nativeTree(resolved, mode) {
  const entries = [];
  for (const [path, entry] of resolved) {
    let v = nativeValue(entry, mode);
    if (entry.token.type === 'typography') {
      const famPath = entry.token.value.fontFamily.slice(1, -1);
      v.fontFamily = nativeValue(resolved.get(famPath), mode);
    }
    entries.push([path, v]);
  }
  return nest(entries);
}

const jsTree = (resolved, mode) => nest([...resolved].map(([p, e]) => [p, e.values[mode]]));

function dtsType(value, indent = '  ') {
  if (Array.isArray(value)) return `readonly ${typeof value[0]}[]`;
  if (value === undefined) return 'string | undefined';
  if (value && typeof value === 'object') {
    const inner = Object.entries(value)
      .map(([k, v]) => `${indent}  readonly ${JSON.stringify(k)}: ${dtsType(v, indent + '  ')};`)
      .join('\n');
    return `{\n${inner}\n${indent}}`;
  }
  return typeof value;
}

function flatIndex(resolved) {
  return [...resolved].map(([path, e]) => {
    const varies = modeDependent(path, e);
    return {
      name: path,
      cssVar: cssVarName(path),
      type: e.token.type,
      layer: e.token.layer,
      description: e.token.description,
      value: varies ? { light: e.values.light, dark: e.values.dark } : e.values.light,
      aliasOf: e.refs.light ? (varies ? { light: e.refs.light, dark: e.refs.dark } : e.refs.light) : undefined,
    };
  });
}

// ---------- main ----------

export function build({ srcDir = SRC_DIR, distDir = DIST } = {}) {
  outDir = distDir;
  const fontCss = join(srcDir, 'fonts', 'fonts.css');
  if (!existsSync(fontCss)) throw new Error(`Missing ${fontCss}: the token sheets inline its @font-face rules`);
  // Drop the file's header comment, point the font urls at where the files sit relative to each sheet.
  const fontFaces = (filesUrl) =>
    readFileSync(fontCss, 'utf8')
      .replace(/^\/\*[\s\S]*?\*\/\s*/, '')
      .replaceAll("url('./", `url('${filesUrl}/`);
  rmSync(distDir, { recursive: true, force: true });
  const resolved = resolveAll(loadTokens({ srcDir }));
  const themes = listThemes(srcDir);
  const resolvedThemes = Object.fromEntries(themes.map((t) => [t.name, resolveAll(loadTokens({ srcDir, theme: t }))]));

  write('css/tokens.css', buildCss(resolved, 'Lock In tokens (default theme)', fontFaces('../fonts')));
  write('css/typography.css', buildTypographyCss(resolved));
  // Web fonts the font-family tokens name. The @font-face rules are inlined into every token sheet (see fontFaces) so one import is enough.
  cpSync(join(srcDir, 'fonts'), join(distDir, 'fonts'), { recursive: true, filter: (f) => !f.endsWith('fonts.css') });
  for (const t of themes) write(`css/themes/${t.name}.css`, buildCss(resolvedThemes[t.name], `Lock In tokens — theme "${t.name}"`, fontFaces('../../fonts')));

  const light = jsTree(resolved, 'light');
  const cssVars = nest([...resolved.keys()].map((p) => [p, `var(${cssVarName(p)})`]));
  const themeTrees = Object.fromEntries(
    Object.entries(resolvedThemes).map(([n, r]) => [n, { light: jsTree(r, 'light'), dark: jsTree(r, 'dark') }]),
  );
  write('js/index.js', `// Generated by @lockin/tokens. Do not edit.
export const tokens = ${JSON.stringify({ light, dark: jsTree(resolved, 'dark') }, null, 2)};
export const themes = ${JSON.stringify(themeTrees, null, 2)};
export const cssVars = ${JSON.stringify(cssVars, null, 2)};
`);
  write('js/index.d.ts', `// Generated by @lockin/tokens.
export type TokenTree = ${dtsType(light, '')};
export type CssVarTree = ${dtsType(cssVars, '')};
export type ColorMode = 'light' | 'dark';
export declare const tokens: Record<ColorMode, TokenTree>;
export declare const themes: Record<${themes.map((t) => JSON.stringify(t.name)).join(' | ') || 'string'}, Record<ColorMode, TokenTree>>;
export declare const cssVars: CssVarTree;
`);

  const nLight = nativeTree(resolved, 'light');
  const nativeThemes = Object.fromEntries(
    Object.entries(resolvedThemes).map(([n, r]) => [n, { light: nativeTree(r, 'light'), dark: nativeTree(r, 'dark') }]),
  );
  write('native/index.js', `// Generated by @lockin/tokens for React Native. Do not edit.
export const nativeTokens = ${JSON.stringify({ light: nLight, dark: nativeTree(resolved, 'dark') }, null, 2)};
export const nativeThemes = ${JSON.stringify(nativeThemes, null, 2)};
`);
  write('native/index.d.ts', `// Generated by @lockin/tokens.
export type NativeTokenTree = ${dtsType(nLight, '')};
export declare const nativeTokens: Record<'light' | 'dark', NativeTokenTree>;
export declare const nativeThemes: Record<string, Record<'light' | 'dark', NativeTokenTree>>;
`);

  write('json/tokens.light.json', JSON.stringify(light, null, 2));
  write('json/tokens.dark.json', JSON.stringify(jsTree(resolved, 'dark'), null, 2));
  write('json/tokens.flat.json', JSON.stringify(flatIndex(resolved), null, 2));
  write('json/themes.json', JSON.stringify(themes, null, 2));

  return { count: resolved.size, themes: themes.map((t) => t.name) };
}

if (process.argv[1]?.replace(/\\/g, '/').endsWith('scripts/build.mjs')) {
  const { count, themes } = build();
  console.log(`✓ Built ${count} tokens (themes: ${themes.join(', ') || 'none'}) → dist/`);
}
